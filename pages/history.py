"""Prediction History page — sortable, filterable history table."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))

import streamlit as st
import pandas as pd
from datetime import datetime
from data.mock_data import MOCK_HISTORY

st.markdown("""
<div class="page-header">
  <div class="page-title">Prediction History</div>
  <div class="page-desc">Every churn prediction generated by the model.</div>
</div>
""", unsafe_allow_html=True)

df = pd.DataFrame(MOCK_HISTORY)
df["date_parsed"] = pd.to_datetime(df["date"])
df["date_fmt"]    = df["date_parsed"].dt.strftime("%b %d, %Y")

# ── Filters ───────────────────────────────────────────────────────────────────

f1, f2, f3 = st.columns([3, 1, 1])
query    = f1.text_input("🔍  Search", placeholder="Customer name or ID…")
risk_fil = f2.selectbox("Risk Level", ["All", "High", "Medium", "Low"])
status_fil = f3.selectbox("Status", ["All", "Completed", "Reviewed", "Action taken"])

if query:
    q    = query.lower()
    mask = (
        df["customer_name"].str.lower().str.contains(q, na=False)
        | df["customer_id"].str.lower().str.contains(q, na=False)
        | df["id"].str.lower().str.contains(q, na=False)
    )
    df = df[mask]

if risk_fil != "All":
    df = df[df["risk_level"] == risk_fil]
if status_fil != "All":
    df = df[df["status"] == status_fil]

df = df.sort_values("date_parsed", ascending=False).reset_index(drop=True)

# ── Summary ───────────────────────────────────────────────────────────────────

s1, s2, s3, s4 = st.columns(4)
s1.metric("Total Records", len(df))
s2.metric("High Risk",  int((df["risk_level"] == "High").sum()))
s3.metric("Action Taken", int((df["status"] == "Action taken").sum()))
s4.metric("Reviewed",   int((df["status"] == "Reviewed").sum()))

st.markdown("<div style='height:8px'></div>", unsafe_allow_html=True)

# ── Table ─────────────────────────────────────────────────────────────────────

RISK_COLORS   = {"High": "#fca5a5", "Medium": "#fcd34d", "Low": "#6ee7b7"}
STATUS_COLORS = {
    "Completed":    ("#a5b4fc", "rgba(99,102,241,.15)"),
    "Reviewed":     ("#fcd34d", "rgba(245,158,11,.15)"),
    "Action taken": ("#6ee7b7", "rgba(16,185,129,.15)"),
}

def status_badge(status: str) -> str:
    color, bg = STATUS_COLORS.get(status, ("#94a3b8", "rgba(255,255,255,0.07)"))
    return (
        f'<span style="background:{bg};color:{color};padding:2px 10px;border-radius:99px;'
        f'font-size:.72rem;font-weight:600">{status}</span>'
    )

st.markdown('<div class="card" style="padding:0;overflow:hidden">', unsafe_allow_html=True)
st.markdown("""
<div style="display:grid;grid-template-columns:1fr 2fr 1fr 1fr 1fr 1fr;gap:8px;
            padding:12px 20px;background:rgba(99,102,241,0.1);
            border-bottom:1px solid rgba(255,255,255,0.06)">
  <div style="font-size:.72rem;color:#64748b;font-weight:600;text-transform:uppercase;letter-spacing:.06em">Pred ID</div>
  <div style="font-size:.72rem;color:#64748b;font-weight:600;text-transform:uppercase;letter-spacing:.06em">Customer</div>
  <div style="font-size:.72rem;color:#64748b;font-weight:600;text-transform:uppercase;letter-spacing:.06em">Date</div>
  <div style="font-size:.72rem;color:#64748b;font-weight:600;text-transform:uppercase;letter-spacing:.06em">Churn %</div>
  <div style="font-size:.72rem;color:#64748b;font-weight:600;text-transform:uppercase;letter-spacing:.06em">Risk</div>
  <div style="font-size:.72rem;color:#64748b;font-weight:600;text-transform:uppercase;letter-spacing:.06em">Status</div>
</div>
""", unsafe_allow_html=True)

rows_html = ""
for _, row in df.iterrows():
    risk  = row["risk_level"]
    color = RISK_COLORS[risk]
    rows_html += f"""
    <div style="display:grid;grid-template-columns:1fr 2fr 1fr 1fr 1fr 1fr;gap:8px;
                padding:12px 20px;border-bottom:1px solid rgba(255,255,255,0.04);
                transition:background .15s ease"
         onmouseover="this.style.background='rgba(99,102,241,0.05)'"
         onmouseout="this.style.background='transparent'">
      <div style="align-self:center;font-size:.82rem;color:#a5b4fc;font-weight:500">{row['id']}</div>
      <div style="align-self:center">
        <div style="font-weight:600;font-size:.88rem;color:#e2e8f0">{row['customer_name']}</div>
        <div style="font-size:.75rem;color:#64748b">{row['customer_id']} · {row['contract']}</div>
      </div>
      <div style="align-self:center;font-size:.82rem;color:#94a3b8">{row['date_fmt']}</div>
      <div style="align-self:center;font-size:.9rem;font-weight:700;color:{color}">{row['probability']*100:.1f}%</div>
      <div style="align-self:center"><span class="badge badge-{risk.lower()}">{risk}</span></div>
      <div style="align-self:center">{status_badge(row['status'])}</div>
    </div>
    """

st.markdown(rows_html, unsafe_allow_html=True)
st.markdown("</div>", unsafe_allow_html=True)
st.markdown(f"<div style='text-align:center;padding:12px;font-size:.8rem;color:#64748b'>"
            f"Showing {len(df)} of {len(MOCK_HISTORY)} records</div>",
            unsafe_allow_html=True)
